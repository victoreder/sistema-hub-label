-- Atribuir plano Ilimitado às contas sem plano
DO $$
BEGIN
  IF to_regclass('public."SAAS_Planos"') IS NOT NULL AND to_regclass('public."SAAS_Contas"') IS NOT NULL THEN
    WITH il AS (SELECT id FROM public."SAAS_Planos" WHERE nome='Ilimitado' LIMIT 1)
