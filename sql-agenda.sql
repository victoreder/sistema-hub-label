-- AGENDA CONFIG (múltiplas por usuário)
CREATE TABLE IF NOT EXISTS public."SAAS_Agenda_Config" (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  "userId"              UUID NOT NULL,
  nome                  TEXT NOT NULL,
  "horaInicio"          TIME,
  "horaFim"             TIME,
  "diasAtendimento"     SMALLINT[],
  "duracaoMinutos"      INTEGER,
  "horasAntesConfirmacao" INTEGER,
  "idConexao"           BIGINT,
  "templateConfirmacao" TEXT,
  CONSTRAINT "SAAS_Agenda_Config_userId_fkey" FOREIGN KEY ("userId") REFERENCES public."SAAS_Usuarios"(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT "SAAS_Agenda_Config_idConexao_fkey" FOREIGN KEY ("idConexao") REFERENCES public."SAAS_Conexões"(id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- AGENDAMENTOS (atendimento — ocupam slot na agenda)
CREATE TABLE IF NOT EXISTS public."SAAS_Agendamentos" (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  "userId"              UUID NOT NULL,
  "idAgendaConfig"      BIGINT NOT NULL,
  "idConexao"           BIGINT,
  "idContato"           BIGINT,
  telefone              TEXT,
  "dataHora"            TIMESTAMPTZ NOT NULL,
  "duracaoMinutos"      INTEGER,
  status                TEXT NOT NULL DEFAULT 'agendado',
  "confirmacaoEnviada"  BOOLEAN NOT NULL DEFAULT false,
  observacoes           TEXT,
  CONSTRAINT "SAAS_Agendamentos_userId_fkey" FOREIGN KEY ("userId") REFERENCES public."SAAS_Usuarios"(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT "SAAS_Agendamentos_idAgendaConfig_fkey" FOREIGN KEY ("idAgendaConfig") REFERENCES public."SAAS_Agenda_Config"(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT "SAAS_Agendamentos_idConexao_fkey" FOREIGN KEY ("idConexao") REFERENCES public."SAAS_Conexões"(id) ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT "SAAS_Agendamentos_idContato_fkey" FOREIGN KEY ("idContato") REFERENCES public."SAAS_Contatos"(id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- AGENDAMENTOS MENSAGENS (não ocupa agenda)
CREATE TABLE IF NOT EXISTS public."SAAS_Agendamentos_Mensagens" (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  "userId"        UUID NOT NULL,
  "idConexao"     BIGINT,
  "idContato"     BIGINT,
  telefone        TEXT,
  mensagem        TEXT,
  "dataHora"      TIMESTAMPTZ NOT NULL,
  status          TEXT NOT NULL DEFAULT 'pendente',
  "enviadoEm"     TIMESTAMPTZ,
  CONSTRAINT "SAAS_Agendamentos_Mensagens_userId_fkey" FOREIGN KEY ("userId") REFERENCES public."SAAS_Usuarios"(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT "SAAS_Agendamentos_Mensagens_idConexao_fkey" FOREIGN KEY ("idConexao") REFERENCES public."SAAS_Conexões"(id) ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT "SAAS_Agendamentos_Mensagens_idContato_fkey" FOREIGN KEY ("idContato") REFERENCES public."SAAS_Contatos"(id) ON UPDATE CASCADE ON DELETE SET NULL
);

