CREATE OR REPLACE FUNCTION public.add_connections_disparo(p_disparo_id bigint, p_conn_ids bigint[], p_user_id uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE hdr record; v_all_conns bigint[]; v_conn_count int; v_idx_conn int := 1; v_cur_ts timestamptz; v_counter int := 0; v_gap int; rec_det record; v_first_ts timestamptz;
BEGIN
  SELECT * INTO hdr FROM public."SAAS_Disparos" WHERE id=p_disparo_id AND "contaId"=p_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Usuário inválido ou disparo inexistente'; END IF;
  SELECT array_agg(DISTINCT conn)::bigint[] INTO v_all_conns FROM unnest(COALESCE(hdr."idConexoes", array[]::bigint[]) || COALESCE(p_conn_ids, array[]::bigint[])) AS conn;
  v_conn_count := COALESCE(array_length(v_all_conns, 1), 0);
  IF v_conn_count = 0 THEN RAISE EXCEPTION 'É necessário fornecer pelo menos 1 conexão válida'; END IF;
  UPDATE public."SAAS_Disparos" SET "idConexoes" = v_all_conns WHERE id = p_disparo_id;
  v_cur_ts := f_next_valid_time(now() + interval '1 minute', hdr."StartTime", hdr."EndTime", COALESCE(hdr."DiasSelecionados", ARRAY[]::smallint[])::int[]);
  FOR rec_det IN SELECT * FROM public."SAAS_Detalhes_Disparos" WHERE "idDisparo"=p_disparo_id AND "Status"='pending' ORDER BY id
  LOOP
    IF hdr."PausaAposMensagens" > 0 AND v_counter > 0 AND v_counter % hdr."PausaAposMensagens" = 0 THEN
      v_cur_ts := v_cur_ts + make_interval(mins => hdr."PausaMinutos");
      v_cur_ts := f_next_valid_time(v_cur_ts, hdr."StartTime", hdr."EndTime", COALESCE(hdr."DiasSelecionados", ARRAY[]::smallint[])::int[]);
    END IF;
    UPDATE public."SAAS_Detalhes_Disparos" SET "idConexao"=v_all_conns[v_idx_conn], "dataEnvio"=v_cur_ts, "mensagemErro"=NULL WHERE id=rec_det.id;
    IF v_counter = 0 THEN v_first_ts := v_cur_ts; END IF;
    v_counter := v_counter + 1; v_idx_conn := (v_idx_conn % v_conn_count) + 1;
    v_gap := hdr."intervaloMin" + floor(random() * (hdr."intervaloMax" - hdr."intervaloMin" + 1))::int;
    v_cur_ts := f_next_valid_time(v_cur_ts + make_interval(secs => v_gap), hdr."StartTime", hdr."EndTime", COALESCE(hdr."DiasSelecionados", ARRAY[]::smallint[])::int[]);
  END LOOP;
  IF v_counter > 0 THEN
    UPDATE public."SAAS_Disparos" SET "StatusDisparo" = CASE WHEN v_first_ts <= now() THEN 'Em andamento' ELSE 'Aguardando' END WHERE id = p_disparo_id;
  END IF;
END;
$$;

-- create_disparo e create_disparo_grupo: payload "userId" = contaId; plano é da SAAS_Contas (não SAAS_Usuarios)
-- SECURITY DEFINER para que INSERT em SAAS_Disparos/SAAS_Detalhes_Disparos não falhe por RLS (acesso já validado via contaId no payload)
CREATE OR REPLACE FUNCTION public.create_disparo(p_payload jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $function$
DECLARE
  v_conta_id   uuid    := (p_payload ->> 'userId')::uuid;
  v_fake_call  boolean := COALESCE((p_payload #>> '{settings,fakecall}')::boolean, false);
  v_messages   jsonb[] := ARRAY(SELECT m FROM jsonb_array_elements(COALESCE(p_payload->'mensagens','[]'::jsonb)) m);
  v_msg_count  int     := COALESCE(array_length(v_messages, 1), 0);
  v_conn_ids   bigint[] := COALESCE(ARRAY(SELECT (c->>'id')::bigint FROM jsonb_array_elements(COALESCE(p_payload->'connections','[]'::jsonb)) c WHERE (c->>'id') ~ '^\d+$'), array[]::bigint[]);
  v_conn_count int := COALESCE(array_length(v_conn_ids,1),0);
  v_list_ids   bigint[] := COALESCE(ARRAY(SELECT (x)::bigint FROM jsonb_array_elements_text(COALESCE(p_payload->'idLista','[]'::jsonb)) x), array[]::bigint[]);
  v_interval_min int := COALESCE((p_payload #>> '{settings,intervalMin}')::int, 30);
  v_interval_max int := COALESCE((p_payload #>> '{settings,intervalMax}')::int, 60);
  v_pause_after int := COALESCE((p_payload #>> '{settings,pauseAfterMessages}')::int, 0);
  v_pause_minutes int := COALESCE((p_payload #>> '{settings,pauseMinutes}')::int, 0);
  v_start_time time := COALESCE((p_payload #>> '{settings,startTime}')::time, time '08:00');
  v_end_time   time := COALESCE((p_payload #>> '{settings,endTime}')::time, time '18:00');
  v_days int[] := COALESCE(ARRAY(SELECT CASE WHEN dtxt='0' THEN 7 ELSE dtxt::int END FROM jsonb_array_elements_text(COALESCE(p_payload->'settings'->'selectedDays','[]'::jsonb)) WITH ORDINALITY AS t(dtxt,ord) WHERE dtxt ~ '^\d+$' ORDER BY ord), array[]::int[]);
  v_schedule_base timestamptz := COALESCE((p_payload #>> '{settings,scheduleData}')::timestamptz, now() + interval '2 minutes');
  v_cur_ts timestamptz; v_disparo_id bigint; v_first_ts timestamptz; v_total int := 0; v_idx_msg int := 1; v_idx_conn int := 1; v_counter int := 0; v_gap int;
  v_msg_obj jsonb; v_template text; v_media_hash text; v_conn_id bigint; v_rendered text; rec_cont record;
  v_limit_plan bigint; v_used_month bigint; v_to_send bigint; v_total_after bigint;
  v_month_start timestamptz := (date_trunc('month', now() AT TIME ZONE 'America/Sao_Paulo') AT TIME ZONE 'America/Sao_Paulo');
  v_next_month  timestamptz := ((date_trunc('month', now() AT TIME ZONE 'America/Sao_Paulo') + interval '1 month') AT TIME ZONE 'America/Sao_Paulo');
BEGIN
  v_cur_ts := f_next_valid_time(v_schedule_base, v_start_time, v_end_time, v_days);
  -- Verificação de limite: plano vem de SAAS_Contas (contaId = payload.userId), não de SAAS_Usuarios
  SELECT p."qntDisparos"::bigint INTO v_limit_plan
    FROM public."SAAS_Contas" conta LEFT JOIN public."SAAS_Planos" p ON p.id = conta.plano
   WHERE conta.id = v_conta_id;
  IF v_limit_plan IS NOT NULL THEN
    SELECT COALESCE(COUNT(*),0)::bigint INTO v_used_month
      FROM public."SAAS_Detalhes_Disparos" d JOIN public."SAAS_Disparos" h ON h.id = d."idDisparo"
     WHERE h."contaId" = v_conta_id AND d."dataEnvio" >= v_month_start AND d."dataEnvio" < v_next_month;
    WITH ids AS (SELECT DISTINCT unnest(v_list_ids) AS id_lista),
    base AS (SELECT DISTINCT c.telefone FROM public."SAAS_Contatos" c JOIN ids ON ids.id_lista = c."idLista"
             WHERE c."contaId" = v_conta_id AND c.telefone IS NOT NULL)
    SELECT COALESCE(COUNT(*),0)::bigint INTO v_to_send FROM base;
    v_total_after := v_used_month + v_to_send;
    IF v_total_after > v_limit_plan THEN
      RAISE EXCEPTION 'limite atingido: % usados + % a enviar = %, limite do plano = %', v_used_month, v_to_send, v_total_after, v_limit_plan USING ERRCODE='P0001';
    END IF;
  END IF;
  INSERT INTO public."SAAS_Disparos" ("Mensagens","TipoDisparo","TotalDisparos","MensagensDisparadas","StatusDisparo","contaId","idListas","idConexoes","intervaloMin","intervaloMax","PausaAposMensagens","PausaMinutos","StartTime","EndTime","DiasSelecionados","DataAgendamento")
  VALUES (v_messages,'Individual',0,0,'Aguardando',v_conta_id,v_list_ids,v_conn_ids,v_interval_min,v_interval_max,v_pause_after,v_pause_minutes,v_start_time,v_end_time,v_days::smallint[],CASE WHEN p_payload #>> '{settings,scheduleData}' IS NOT NULL THEN v_schedule_base ELSE NULL END)
  RETURNING id INTO v_disparo_id;
  FOR rec_cont IN
    WITH ids AS (SELECT DISTINCT unnest(v_list_ids) AS id_lista)
    SELECT DISTINCT ON (c.telefone) c.id, c.telefone, c.nome, c.atributos
      FROM public."SAAS_Contatos" c JOIN ids ON ids.id_lista = c."idLista"
     WHERE c."contaId" = v_conta_id AND c.telefone IS NOT NULL ORDER BY c.telefone, c.id
  LOOP
    v_msg_obj := v_messages[v_idx_msg]; v_idx_msg := (v_idx_msg % v_msg_count) + 1;
    v_template := v_msg_obj->>'text'; v_media_hash := NULLIF(COALESCE(v_msg_obj->'media'->>'link', v_msg_obj->'media'->>'hashredis',''),'');
    v_conn_id := CASE WHEN v_conn_count > 0 THEN v_conn_ids[v_idx_conn] END;
    IF v_conn_count > 0 THEN v_idx_conn := (v_idx_conn % v_conn_count) + 1; END IF;
    IF v_pause_after > 0 AND v_counter > 0 AND v_counter % v_pause_after = 0 THEN
      v_cur_ts := f_next_valid_time(v_cur_ts + make_interval(mins => v_pause_minutes), v_start_time, v_end_time, v_days);
    END IF;
    v_rendered := f_render_message(v_template, rec_cont.nome, rec_cont.atributos, v_cur_ts);
    INSERT INTO public."SAAS_Detalhes_Disparos" ("idDisparo","idContato","Mensagem","idConexao","dataEnvio","Status","KeyRedis","FakeCall")
    VALUES (v_disparo_id, rec_cont.id, v_rendered, v_conn_id, v_cur_ts, 'pending', v_media_hash, v_fake_call);
    IF v_total = 0 THEN v_first_ts := v_cur_ts; END IF;
    v_total := v_total + 1; v_counter := v_counter + 1;
    v_gap := v_interval_min + floor(random() * (v_interval_max - v_interval_min + 1))::int;
    v_cur_ts := f_next_valid_time(v_cur_ts + make_interval(secs => v_gap), v_start_time, v_end_time, v_days);
  END LOOP;
  UPDATE public."SAAS_Disparos" SET "TotalDisparos"=v_total, "StatusDisparo"=CASE WHEN v_first_ts > now() THEN 'Aguardando' ELSE 'Em andamento' END WHERE id=v_disparo_id;
  RETURN v_disparo_id;
END $function$;

-- create_disparo_grupo: SECURITY DEFINER para não falhar por RLS ao inserir em SAAS_Detalhes_Disparos
CREATE OR REPLACE FUNCTION public.create_disparo_grupo(p_payload jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $function$
DECLARE
  v_conta_id   uuid := (p_payload->>'userId')::uuid;
  v_mention_all boolean := coalesce((p_payload#>>'{settings,mencionarTodos}')::boolean,false);
  v_messages jsonb[] := ARRAY(SELECT m FROM jsonb_array_elements(COALESCE(p_payload->'mensagens','[]'::jsonb)) m);
  v_msg_count int := coalesce(array_length(v_messages,1),0);
  v_conn_id bigint := (SELECT (c->>'id')::bigint FROM jsonb_array_elements(COALESCE(p_payload->'connections','[]'::jsonb)) c WHERE (c->>'id') ~ '^\d+$' ORDER BY 1 LIMIT 1);
  v_list_ids bigint[] := COALESCE(ARRAY(SELECT (x)::bigint FROM jsonb_array_elements_text(COALESCE(p_payload->'idLista','[]'::jsonb)) x), array[]::bigint[]);
  v_month_start timestamptz := (date_trunc('month', now() AT TIME ZONE 'America/Sao_Paulo') AT TIME ZONE 'America/Sao_Paulo');
  v_next_month timestamptz := ((date_trunc('month', now() AT TIME ZONE 'America/Sao_Paulo') + interval '1 month') AT TIME ZONE 'America/Sao_Paulo');
  v_limit_plan bigint; v_used_month bigint; v_to_send bigint; v_total_after bigint;
  v_schedule_base timestamptz := COALESCE((p_payload#>>'{settings,scheduleData}')::timestamptz, now() + interval '2 minutes');
  v_cur_ts timestamptz := v_schedule_base; v_disparo_id bigint; v_first_ts timestamptz; v_total int := 0; v_idx_msg int := 1;
  v_msg_obj jsonb; v_template text; v_media_hash text; v_rendered text; rec_grupo record;
BEGIN
  -- Verificação de limite: plano vem de SAAS_Contas (contaId = payload.userId), não de SAAS_Usuarios
  SELECT p."qntDisparos"::bigint INTO v_limit_plan
    FROM public."SAAS_Contas" conta LEFT JOIN public."SAAS_Planos" p ON p.id = conta.plano
   WHERE conta.id = v_conta_id;
  IF v_limit_plan IS NOT NULL THEN
    SELECT COALESCE(COUNT(*),0)::bigint INTO v_used_month
      FROM public."SAAS_Detalhes_Disparos" d JOIN public."SAAS_Disparos" h ON h.id = d."idDisparo"
     WHERE h."contaId" = v_conta_id AND d."dataEnvio" >= v_month_start AND d."dataEnvio" < v_next_month;
    WITH ids AS (SELECT DISTINCT unnest(v_list_ids) AS id_lista),
    base AS (SELECT DISTINCT g."WhatsAppId" FROM public."SAAS_Grupos" g JOIN ids ON ids.id_lista = g."idLista"
             WHERE g."contaId"=v_conta_id AND g."WhatsAppId" IS NOT NULL)
    SELECT COALESCE(COUNT(*),0)::bigint INTO v_to_send FROM base;
    v_total_after := v_used_month + v_to_send;
    IF v_total_after > v_limit_plan THEN
      RAISE EXCEPTION 'limite atingido: % usados + % a enviar = %, limite do plano = %', v_used_month, v_to_send, v_total_after, v_limit_plan USING ERRCODE='P0001';
    END IF;
  END IF;
  INSERT INTO public."SAAS_Disparos" ("Mensagens","TipoDisparo","TotalDisparos","MensagensDisparadas","StatusDisparo","contaId","idListas","idConexoes","DataAgendamento")
  VALUES (v_messages,'Grupos',0,0,'Aguardando',v_conta_id,v_list_ids,CASE WHEN v_conn_id IS NOT NULL THEN ARRAY[v_conn_id] ELSE NULL END,v_schedule_base)
  RETURNING id INTO v_disparo_id;
  FOR rec_grupo IN
    WITH ids AS (SELECT unnest(v_list_ids) AS id_lista)
    SELECT DISTINCT ON (g."WhatsAppId") g.id, g."WhatsAppId", g.nome, g.atributos
      FROM public."SAAS_Grupos" g JOIN ids ON ids.id_lista = g."idLista"
     WHERE g."contaId"=v_conta_id AND g."WhatsAppId" IS NOT NULL ORDER BY g."WhatsAppId", g.id
  LOOP
    v_msg_obj := v_messages[v_idx_msg]; v_idx_msg := (v_idx_msg % v_msg_count) + 1;
    v_template := v_msg_obj->>'text'; v_media_hash := NULLIF(COALESCE(v_msg_obj->'media'->>'link', v_msg_obj->'media'->>'hashredis',''),'');
    v_rendered := public.f_render_message(v_template, rec_grupo.nome, rec_grupo.atributos, v_cur_ts);
    INSERT INTO public."SAAS_Detalhes_Disparos" ("idDisparo","idContato","idGrupo","Mensagem","idConexao","dataEnvio","Status","KeyRedis","FakeCall")
    VALUES (v_disparo_id, NULL, rec_grupo.id, v_rendered, v_conn_id, v_cur_ts, 'pending', v_media_hash, v_mention_all);
    IF v_total = 0 THEN v_first_ts := v_cur_ts; END IF;
    v_total := v_total + 1; v_cur_ts := v_cur_ts + interval '15 seconds';
  END LOOP;
  UPDATE public."SAAS_Disparos" SET "TotalDisparos"=v_total, "StatusDisparo"=CASE WHEN v_first_ts > now() THEN 'Aguardando' ELSE 'Em andamento' END WHERE id=v_disparo_id;
  RETURN v_disparo_id;
END $function$;

CREATE OR REPLACE FUNCTION public.f_upsert_conversas_agentes(p_items jsonb)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE v_item jsonb; v_inserted int := 0; v_skipped int := 0; v_exists boolean; v_telefone text; v_idconexao bigint; v_items jsonb;
BEGIN
  IF p_items IS NULL THEN RETURN jsonb_build_object('inserted', 0, 'skipped', 0, 'error', 'payload null'); END IF;
  IF jsonb_typeof(p_items) = 'array' THEN v_items := p_items;
  ELSIF jsonb_typeof(p_items) = 'object' AND (p_items ? 'data') AND jsonb_typeof(p_items->'data') = 'array' THEN v_items := p_items->'data';
  ELSE RETURN jsonb_build_object('inserted', 0, 'skipped', 0, 'error', 'payload deve ser array ou {"data": [...]}', 'received_type', jsonb_typeof(p_items)); END IF;
  IF jsonb_array_length(v_items) = 0 THEN RETURN jsonb_build_object('inserted', 0, 'skipped', 0, 'error', 'array vazio'); END IF;
  FOR v_item IN SELECT * FROM jsonb_array_elements(v_items) LOOP
    v_telefone := NULLIF(trim(v_item->>'telefone'), ''); v_idconexao := (v_item->>'idConexao')::bigint;
    IF v_telefone IS NULL AND v_idconexao IS NULL THEN CONTINUE; END IF;
    SELECT EXISTS (SELECT 1 FROM public."SAAS_Conversas_Agentes" WHERE (telefone IS NOT DISTINCT FROM v_telefone) AND ("idConexao" IS NOT DISTINCT FROM v_idconexao)) INTO v_exists;
    IF v_exists THEN v_skipped := v_skipped + 1; CONTINUE; END IF;
    INSERT INTO public."SAAS_Conversas_Agentes" (telefone, "nomeConversa", "statusAtendimento", "idConexao", pausado, "contaId", lida, "fotoPerfil")
    VALUES (v_telefone, NULLIF(trim(v_item->>'nomeConversa'), ''), COALESCE(NULLIF(trim(lower(v_item->>'statusAtendimento')), ''), 'aberto'), v_idconexao,
            COALESCE((v_item->>'pausado')::boolean, false), (v_item->>'userId')::uuid, COALESCE((v_item->>'lida')::boolean, false), NULLIF(trim(v_item->>'fotoPerfil'), ''));
    v_inserted := v_inserted + 1;
  END LOOP;
  RETURN jsonb_build_object('inserted', v_inserted, 'skipped', v_skipped);
EXCEPTION WHEN OTHERS THEN RETURN jsonb_build_object('inserted', v_inserted, 'skipped', v_skipped, 'error', SQLERRM);
END;
$$;

CREATE OR REPLACE FUNCTION public.f_inserir_mensagens_conversa(p_mensagens jsonb, p_user_id uuid, p_conversa_id bigint, p_conexao_id bigint)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE v_item jsonb; v_items jsonb; v_inserted int := 0; v_skipped int := 0; v_msg_text text; v_tipo text; v_arquivo text; v_from_me boolean; v_ev_id text; v_respondida text; v_created timestamptz;
BEGIN
  IF p_mensagens IS NULL THEN RETURN jsonb_build_object('inserted', 0, 'skipped', 0, 'error', 'payload null'); END IF;
  IF jsonb_typeof(p_mensagens) = 'array' THEN v_items := p_mensagens;
  ELSIF jsonb_typeof(p_mensagens) = 'object' AND (p_mensagens ? 'data') AND jsonb_typeof(p_mensagens->'data') = 'array' THEN v_items := p_mensagens->'data';
  ELSE RETURN jsonb_build_object('inserted', 0, 'skipped', 0, 'error', 'payload deve ser array ou {"data": [...]}'); END IF;
  IF jsonb_array_length(v_items) = 0 THEN RETURN jsonb_build_object('inserted', 0, 'skipped', 0, 'error', 'array vazio'); END IF;
  FOR v_item IN SELECT * FROM jsonb_array_elements(v_items) LOOP
    v_ev_id := NULLIF(trim(v_item->>'id'), '');
    IF v_ev_id IS NOT NULL AND EXISTS (SELECT 1 FROM public."SAAS_Mensagens" WHERE "messageEvolutionId" = v_ev_id AND "conversaId" = p_conversa_id) THEN v_skipped := v_skipped + 1; CONTINUE; END IF;
    v_tipo := COALESCE(NULLIF(trim(lower(v_item->>'messageType')), ''), 'conversation'); v_from_me := COALESCE((v_item->'key'->>'fromMe')::boolean, false);
    v_msg_text := v_item->'message'->>'conversation'; IF v_msg_text IS NULL THEN v_msg_text := v_item->'message'->'extendedTextMessage'->>'text'; END IF;
    IF v_msg_text IS NULL THEN v_msg_text := v_item->'message'->'imageMessage'->>'caption'; END IF;
    IF v_msg_text IS NULL THEN v_msg_text := v_item->'message'->'videoMessage'->>'caption'; END IF;
    IF v_msg_text IS NULL THEN v_msg_text := v_item->'message'->'documentMessage'->>'caption'; END IF;
